-- 테이블 생성
-- 회원 테이블
CREATE TABLE final_member (
    num NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,		-- 회원번호
    id VARCHAR2(30) UNIQUE NOT NULL,										-- 회원 아이디
    pass VARCHAR2(30) NOT NULL,												-- 비밀번호
    name VARCHAR2(50),														-- 회원이름
    nickname VARCHAR2(30) UNIQUE NOT NULL,									-- 닉네임
    phone VARCHAR2(20),														-- 전화번호
    email VARCHAR2(50),														-- 이메일
    gender VARCHAR2(10),													-- 성별(남성,여성)
    age NUMBER(3)															-- 나이
);

-- 영화 테이블
CREATE TABLE final_movie (
	movie_code NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, 	-- 영화 코드
	title VARCHAR2(150) NOT NULL,												-- 영화 제목
	director VARCHAR2(30) NOT NULL,												-- 감독명
	genre VARCHAR2(50),															-- 장르
	release_date DATE NOT NULL,													-- 개봉일
	age_limit NUMBER(3),														-- 관람연령제한
	story CLOB,																	-- 줄거리
	running_time NUMBER NOT NULL												-- 상영시간(분단위)
	-- 포스터 이미지
);

-- 댓글 테이블
CREATE TABLE movie_comment(
	comment_num NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, 	-- 댓글 번호
	member_id VARCHAR2(30) NOT NULL REFERENCES final_member(id),			-- 회원 아이디
	movie_code NUMBER NOT NULL REFERENCES final_movie(movie_code), 				-- 영화 코드
	content CLOB,																-- 댓글 내용
	score NUMBER NOT NULL,														-- 별점					
	reg_date DATE DEFAULT SYSDATE,												-- 게시 날짜
	update_date DATE															-- 수정 날짜
);

-- 영화관 종류(메가박스, CGV 등)
CREATE TABLE theater(
	theater_code NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,	-- 영화관 코드
	theater_name VARCHAR2(20)													-- 영화관 이름
);

-- 영화관 지점 테이블
CREATE TABLE theater_branch(
	theater_code NUMBER NOT NULL REFERENCES theater(theater_code),				-- 영화관 코드	
	branch_code NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,	-- 지점 코드
	branch_name VARCHAR2(30) NOT NULL,											-- 지점명
	addr VARCHAR2(150) NOT NULL,												-- 주소
	phone VARCHAR2(30)															-- 연락처
);

-- 지점별 상영관 테이블
CREATE TABLE branch_screen(
	branch_code NUMBER NOT NULL REFERENCES theater_branch(branch_code),			-- 지점 코드
	screen_code NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,	-- 상영관 코드
	screen_name VARCHAR2(30) NOT NULL,											-- 상영관 이름(1관 2관 등)
	screen_type VARCHAR2(30) NOT NULL											-- 상영관 종류(2D, 돌비 등)
);

CREATE TABLE schedule (
	schedule_code NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
	movie_code NUMBER NOT NULL REFERENCES final_movie(movie_code),
	screen_code NUMBER NOT NULL REFERENCES branch_screen(screen_code),
	start_time DATE NOT NULL,
	end_time date
);

