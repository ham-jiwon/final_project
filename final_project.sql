INSERT INTO team_member(id, pass, name, addr, phone, gender, age)
SELECT
	-- user1, user2, user3 ... user10000
	'user' || LEVEL AS id,
	
	-- pass1, pass2, pass3 ... pass10000
	'pass' || LEVEL AS pass,
	
	-- 사용자1, 사용자2, 사용자3 ... 사용자10000
	'사용자' || LEVEL AS name,
	
	CASE WHEN MOD(LEVEL, 2) = 1 THEN '부산' ELSE '서울' END AS addr,
	'01012345678' AS phone,
	CASE WHEN MOD(LEVEL, 2) = 1 THEN '남성' ELSE '여성' END AS gender,
	
	-- 나이 (20 ~ 70세 랜덤)
	TRUNC(DBMS_RANDOM.VALUE(20, 70)) AS age
	
FROM DUAL
CONNECT BY LEVEL <= 10000;

