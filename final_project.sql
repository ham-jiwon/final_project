-- CONNECT BY LEVEL <= 40
-- 1부터 40까지의 자동 증가 숫자 생성
-- SELECT LEVEL FROM DUAL : LEVEL => 계츨 쿼리에서 자동 증하가는 가상 컬럼

SELECT 
	LEVEL
FROM DUAL
CONNECT BY LEVEL <= 40;


